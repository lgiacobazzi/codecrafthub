"""
CodeCraftHub Course REST API

Run with:
    pip install Flask
    python app.py

The API stores courses in courses.json and does not require a database.
"""

import json
import os
import tempfile
from datetime import datetime, timezone

from flask import Flask, jsonify, request, url_for


app = Flask(__name__)

# Store courses.json in the same directory as this app.py file.
DATA_FILE = os.path.join(os.path.dirname(__file__), "courses.json")

ALLOWED_STATUSES = {
    "Not Started",
    "In Progress",
    "Completed",
}

REQUIRED_FIELDS = {
    "name",
    "description",
    "target_date",
    "status",
}


class StorageError(Exception):
    """Raised when the course JSON file cannot be read or written."""


def load_courses():
    """
    Load courses from courses.json.

    If the file does not exist, create it with an empty list.
    Corrupted files are not overwritten because that could destroy data.
    """

    if not os.path.exists(DATA_FILE):
        save_courses([])
        return []

    try:
        with open(DATA_FILE, "r", encoding="utf-8") as file:
            courses = json.load(file)

    except (json.JSONDecodeError, UnicodeDecodeError) as error:
        raise StorageError(
            "courses.json contains invalid or corrupted data"
        ) from error

    except OSError as error:
        raise StorageError("Unable to read courses.json") from error

    # The top-level JSON value must be an array.
    if not isinstance(courses, list):
        raise StorageError("courses.json must contain a JSON array")

    # Validate the minimum structure of every stored course.
    for index, course in enumerate(courses):
        if not isinstance(course, dict):
            raise StorageError(
                f"Course at index {index} must be a JSON object"
            )

        if "id" not in course:
            raise StorageError(
                f"Course at index {index} is missing an id"
            )

        # IDs generated by this application are positive integers.
        if (
            isinstance(course["id"], bool)
            or not isinstance(course["id"], int)
            or course["id"] < 1
        ):
            raise StorageError(
                f"Course at index {index} has an invalid id"
            )

    return courses


def save_courses(courses):
    """
    Save courses using an atomic file replacement.

    The data is first written to a temporary file. Once that succeeds,
    os.replace() replaces the original file in one operation.
    """

    directory = os.path.dirname(DATA_FILE) or "."
    temporary_path = None

    try:
        # Keep the temporary file in the same directory as courses.json.
        # This helps ensure os.replace() is atomic.
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=directory,
            prefix="courses-",
            suffix=".tmp",
            delete=False,
        ) as temporary_file:
            temporary_path = temporary_file.name

            json.dump(courses, temporary_file, indent=2)
            temporary_file.write("\n")

            # Make sure all data is written before replacing the file.
            temporary_file.flush()
            os.fsync(temporary_file.fileno())

        # Replace the old file only after the temporary file is complete.
        os.replace(temporary_path, DATA_FILE)

    except OSError as error:
        # Remove the temporary file if something failed.
        if temporary_path and os.path.exists(temporary_path):
            try:
                os.remove(temporary_path)
            except OSError:
                pass

        raise StorageError("Unable to write courses.json") from error


def validate_course_payload(payload):
    """
    Validate a request body for creating or replacing a course.

    Returns:
        None if valid, otherwise an error message.
    """

    if not isinstance(payload, dict):
        return "Request body must be a JSON object"

    # Require exactly the expected client-provided fields.
    missing_fields = REQUIRED_FIELDS - set(payload.keys())
    if missing_fields:
        return (
            "Missing required fields: "
            + ", ".join(sorted(missing_fields))
        )

    unknown_fields = set(payload.keys()) - REQUIRED_FIELDS
    if unknown_fields:
        return "Unknown fields: " + ", ".join(sorted(unknown_fields))

    # Validate name.
    if not isinstance(payload["name"], str):
        return "name must be a string"

    if not payload["name"].strip():
        return "name is required and cannot be empty"

    # Validate description.
    if not isinstance(payload["description"], str):
        return "description must be a string"

    if not payload["description"].strip():
        return "description is required and cannot be empty"

    # Validate target_date.
    target_date = payload["target_date"]

    if not isinstance(target_date, str):
        return "target_date must be a string"

    try:
        parsed_date = datetime.strptime(target_date, "%Y-%m-%d")

        # This also rejects formats such as 2026-1-2.
        if parsed_date.strftime("%Y-%m-%d") != target_date:
            return "target_date must use YYYY-MM-DD format"

    except ValueError:
        return "target_date must be a valid date in YYYY-MM-DD format"

    # Check the type before testing membership in the set.
    status = payload["status"]

    if not isinstance(status, str):
        return "status must be a string"

    if status not in ALLOWED_STATUSES:
        return (
            'status must be one of: "Not Started", '
            '"In Progress", "Completed"'
        )

    return None


def find_course(courses, course_id):
    """Find and return a course by ID, or return None."""

    return next(
        (course for course in courses if course["id"] == course_id),
        None,
    )


def get_next_course_id(courses):
    """
    Generate the next integer ID.

    The first course receives ID 1. If courses already exist, the next
    ID is one greater than the highest existing ID.
    """

    if not courses:
        return 1

    return max(course["id"] for course in courses) + 1


def get_json_payload():
    """
    Read a JSON request body.

    Returns:
        (payload, None) when valid
        (None, error_message) when invalid
    """

    if not request.is_json:
        return None, "Content-Type must be application/json"

    payload = request.get_json(silent=True)

    if payload is None:
        return None, "Request body contains invalid JSON"

    return payload, None


@app.errorhandler(StorageError)
def handle_storage_error(error):
    """Return a JSON 500 response for file-related errors."""

    app.logger.error("Storage error: %s", error)

    return jsonify({
        "error": "Course data is currently unavailable"
    }), 500


@app.post("/api/courses")
def create_course():
    """Create a new course."""

    payload, error = get_json_payload()

    if error:
        return jsonify({"error": error}), 400

    validation_error = validate_course_payload(payload)

    if validation_error:
        return jsonify({"error": validation_error}), 400

    courses = load_courses()

    course = {
        "id": get_next_course_id(courses),
        "name": payload["name"].strip(),
        "description": payload["description"].strip(),
        "target_date": payload["target_date"],
        "status": payload["status"],
        "created_at": datetime.now(timezone.utc).isoformat(),
    }

    courses.append(course)
    save_courses(courses)

    response = jsonify(course)
    response.status_code = 201

    # Location identifies the newly created resource.
    response.headers["Location"] = url_for(
        "get_course",
        course_id=course["id"],
    )

    return response


@app.get("/api/courses")
def get_courses():
    """Return all courses."""

    courses = load_courses()
    return jsonify(courses), 200


@app.get("/api/courses/<int:course_id>")
def get_course(course_id):
    """Return one course by ID."""

    courses = load_courses()
    course = find_course(courses, course_id)

    if course is None:
        return jsonify({"error": "Course not found"}), 404

    return jsonify(course), 200


@app.put("/api/courses/<int:course_id>")
def update_course(course_id):
    """
    Replace an existing course.

    PUT requires all editable course fields. The ID and created_at timestamp
    are preserved by the server.
    """

    payload, error = get_json_payload()

    if error:
        return jsonify({"error": error}), 400

    validation_error = validate_course_payload(payload)

    if validation_error:
        return jsonify({"error": validation_error}), 400

    courses = load_courses()
    course = find_course(courses, course_id)

    if course is None:
        return jsonify({"error": "Course not found"}), 404

    # Update only client-editable fields.
    course["name"] = payload["name"].strip()
    course["description"] = payload["description"].strip()
    course["target_date"] = payload["target_date"]
    course["status"] = payload["status"]

    save_courses(courses)

    return jsonify(course), 200


@app.delete("/api/courses/<int:course_id>")
def delete_course(course_id):
    """Delete a course by ID."""

    courses = load_courses()
    course = find_course(courses, course_id)

    if course is None:
        return jsonify({"error": "Course not found"}), 404

    courses.remove(course)
    save_courses(courses)

    # A successful DELETE has no response body.
    return "", 204


if __name__ == "__main__":
    # threaded=False prevents concurrent requests from reading and writing
    # the JSON file at the same time and losing updates.
    app.run(
        debug=True,
        threaded=False,
    )